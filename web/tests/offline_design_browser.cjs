/* v2 demo task boundaries, author reveal, media matching and persistent drafts. */
const assert = require('node:assert/strict');
const {chromium} = require('playwright');
(async () => {
  const browser = await chromium.launch({headless:true,args:['--no-sandbox']});
  const page = await browser.newPage({viewport:{width:1440,height:1000}});
  const errors=[], references=[];
  page.on('pageerror', error => errors.push(error.message));
  page.on('request', req => {if(new URL(req.url()).pathname.endsWith('/reference')) references.push(req.url());});
  const base=process.env.REVIEW_TEST_URL || 'http://127.0.0.1:8000';
  try {
    await page.goto(base+'/offline-demo?bank=design-v2');
    await page.waitForSelector('#revealReference');
    assert.equal(await page.locator('#itemNav button').count(),24);
    assert.equal(await page.locator('#bankSelect').inputValue(),'design-v2');
    assert.equal(references.length,0);
    assert.equal(await page.locator('#referenceBody').innerText(),'');
    await page.selectOption('#taskFilter','T2');
    assert.equal(await page.locator('#itemNav button').count(),8);
    await page.locator('#advancedFilters summary').click();
    await page.selectOption('#capabilityFilter','temporal_dynamics_reasoning');
    assert.equal(await page.locator('#itemNav button').count(),2);
    await page.selectOption('#difficultyFilter','hard');
    assert.equal(await page.locator('#itemNav button').count(),2);
    await page.locator('[data-id="SFD2-020"]').click();
    await page.waitForSelector('#sharedEnding');
    assert.equal(await page.locator('[data-history]').count(),2);
    assert.equal(await page.locator('#sharedEnding').count(),1);
    await page.locator('input[name=answer][value=A]').check();
    assert.equal(await page.locator('#modelAnswer').innerText(),'{"answer":"A"}');
    await page.locator('#humanReviewFields summary').click();
    await page.fill('#rationale','浏览器自动化草稿，不是人工核验。');
    await page.reload();
    await page.waitForSelector('#revealReference');
    assert.equal(await page.locator('input[name=answer]:checked').inputValue(),'A');
    await page.click('#revealReference');
    await page.waitForSelector('#referenceBody table');
    assert.match(await page.locator('#referenceBody').innerText(),/难度依据/);
    assert.match(await page.locator('#referenceBody').innerText(),/受控历史编辑/);
    assert.equal(references.length,1);
    await page.selectOption('#taskFilter','T3');
    await page.locator('#advancedFilters summary').click();
    await page.selectOption('#capabilityFilter','');
    await page.selectOption('#difficultyFilter','');
    await page.locator('[data-id="SFD2-022"]').click();
    await page.waitForSelector('.candidate');
    assert.deepEqual(await page.locator('.candidate strong').allTextContents(),['行动 1','行动 2','行动 3']);
    assert.match(await page.locator('#workspace').innerText(),/受控写作示例/);
    assert.equal(await page.locator('#referenceBody').innerText(),'');
    await page.selectOption('#modality','text+video');
    assert.match(await page.locator('#mediaClips').innerText(),/没有.*配对视频/);
    await page.locator('[data-id="SFD2-011"]').click();
    await page.waitForSelector('#modality');
    await page.selectOption('#modality','text+video');
    await page.waitForFunction(()=>document.querySelector('video')?.readyState>=1);
    await page.click('#revealReference');
    await page.waitForSelector('#referenceBody table');
    assert.match(await page.locator('#referenceBody').innerText(),/窗口完整/);
    await page.setViewportSize({width:390,height:844});
    assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+2),'mobile overflow');
    assert.deepEqual(errors,[]);
    console.log(JSON.stringify({passed:true,items:24,checks:['filters','T2 shared expression','answer draft persistence','reference isolation','difficulty reasons','numbered actions','missing media','paired media playback','source branches','mobile layout']}));
  } finally {await browser.close();}
})().catch(error=>{console.error(error);process.exitCode=1;});
