/* Real browser checks against the frozen development bank; no model calls. */
const assert = require('node:assert/strict');
const fs = require('node:fs/promises');
const os = require('node:os');
const path = require('node:path');
const {chromium} = require('playwright');

(async () => {
  const browser = await chromium.launch({headless: true, args: ['--no-sandbox']});
  const context = await browser.newContext({viewport: {width: 1440, height: 1000}, acceptDownloads: true});
  const page = await context.newPage();
  const base = process.env.REVIEW_TEST_URL || 'http://127.0.0.1:8000';
  const output = process.env.REVIEW_TEST_OUTPUT || path.join(os.tmpdir(), 'socialflux-offline-review-browser');
  const errors = [], referenceRequests = [];
  page.on('pageerror', e => errors.push(e.message));
  page.on('request', r => {if (new URL(r.url()).pathname.endsWith('/reference')) referenceRequests.push(r.url());});
  try {
    await fs.mkdir(output, {recursive: true});
    await page.goto(base + '/offline-review?bank=dev60#SFO-005');
    await page.waitForSelector('#sharedEnding');
    assert.equal(await page.locator('#itemNav button').count(), 60);
    assert.equal(await page.locator('[data-history]').count(), 2);
    assert.equal(referenceRequests.length, 0, 'references must not be fetched by default');
    assert.equal(await page.locator('#referenceBody').innerText(), '');
    assert.match(await page.locator('#sharedEnding').innerText(), /相同的当前表达/);
    await page.selectOption('#taskFilter', 'T2');
    assert.equal(await page.locator('#itemNav button').count(), 20);
    await page.selectOption('#shapeFilter', 'combo');
    assert.equal(await page.locator('#itemNav button').count(), 5);
    await page.selectOption('#shapeFilter', '');
    await page.fill('#search', 'GPT50_003');
    assert.equal(await page.locator('#itemNav button').count(), 4);
    await page.fill('#search', '');
    await page.selectOption('#taskFilter', '');
    await page.selectOption('#statusFilter', 'replay_pending');
    assert.equal(await page.locator('#itemNav button').count(), 4);
    await page.selectOption('#statusFilter', '');
    await page.selectOption('#modality', 'text+video');
    await page.waitForFunction(() => document.querySelector('video')?.readyState >= 1);
    assert.match(await page.locator('#mediaClips').innerText(), /A:t1、B:t1/);
    const videoURL = await page.locator('video').getAttribute('src');
    const range = await context.request.get(base + videoURL, {headers: {Range: 'bytes=0-63'}});
    assert.equal(range.status(), 206);
    assert.equal((await range.body()).length, 64);
    await page.fill('#reviewer', 'BROWSER_TEST_ONLY');
    await page.locator('input[name=answer][value=B]').check();
    await page.locator('input[name=evidence][value="A:t2"]').check();
    await page.fill('#rationale', '自动化界面测试草稿，不是人工标注。');
    for (const id of ['clarity', 'evidence_support', 'answer_distinguishability', 'analyzability']) await page.selectOption('#' + id, 'yes');
    await page.selectOption('#decision', 'usable');
    await page.click('#completeButton');
    assert.match(await page.locator('#annotationStatus').innerText(), /已完成/);
    await page.reload();
    await page.waitForSelector('#annotationStatus');
    assert.equal(await page.locator('input[name=answer]:checked').inputValue(), 'B');
    assert.match(await page.locator('#annotationStatus').innerText(), /未查看作者参考/);
    const downloadPromise = page.waitForEvent('download');
    await page.click('#exportButton');
    const download = await downloadPromise, exportPath = await download.path();
    const exported = JSON.parse(await fs.readFile(exportPath, 'utf8'));
    assert.equal(exported.annotations['SFO-005'].status, 'complete');
    assert.equal(exported.annotations['SFO-005'].reviewed_by, 'BROWSER_TEST_ONLY');
    assert.equal(exported.status, 'human_review_draft_not_formal_ground_truth');
    assert.ok(exported.annotations['SFO-005'].modalities_seen.includes('text+video'));
    await page.click('#revealReference');
    await page.waitForSelector('#referenceBody table');
    assert.equal(referenceRequests.length, 1);
    assert.match(await page.locator('#annotationStatus').innerText(), /已看过作者参考/);
    await page.locator('input[name=answer][value=C]').check();
    await page.locator('#importFile').setInputFiles({name: 'backup.json', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify(exported))});
    await page.waitForFunction(() => document.querySelector('#message')?.textContent.includes('标注已导入'));
    assert.equal(await page.locator('input[name=answer]:checked').inputValue(), 'B');
    assert.match(await page.locator('#annotationStatus').innerText(), /已看过作者参考/, 'older import must not erase exposure');
    const corrupt = structuredClone(exported); corrupt.annotations['SFO-005'].answer = 'Z';
    await page.locator('#importFile').setInputFiles({name: 'invalid.json', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify(corrupt))});
    await page.waitForFunction(() => document.querySelector('#message')?.textContent.includes('导入失败'));
    assert.equal(await page.locator('input[name=answer]:checked').inputValue(), 'B');
    corrupt.bank_sha256 = 'wrong-version';
    await page.locator('#importFile').setInputFiles({name: 'wrong-version.json', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify(corrupt))});
    await page.waitForFunction(() => document.querySelector('#message')?.textContent.includes('版本不匹配'));
    await page.locator('[data-id="SFO-009"]').click();
    await page.waitForSelector('#revealReference');
    assert.equal(await page.locator('#referenceBody').innerText(), '');
    assert.equal(referenceRequests.length, 1);
    await page.click('#revealReference');
    await page.waitForSelector('#referenceBody table');
    assert.match(await page.locator('#referenceBody').innerText(), /action_1 · 后续 5 次回应 · 窗口完整/);
    await page.locator('[data-id="SFO-033"]').click();
    await page.waitForSelector('#annotation');
    assert.match(await page.locator('#workspace').innerText(), /完整分支回放尚未完成/);
    await page.locator('[data-id="SFO-005"]').click();
    await page.waitForSelector('#sharedEnding');
    await page.evaluate(() => {window.scrollTo(0, 0); document.querySelector('#message').textContent = '';});
    await page.screenshot({path: path.join(output, 'desktop.png')});
    await page.setViewportSize({width: 390, height: 844});
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1), 'mobile overflow');
    await page.screenshot({path: path.join(output, 'mobile.png')});
    assert.deepEqual(errors, []);
    console.log(JSON.stringify({passed: true, checks: ['T1–T3 filters', 'T2 histories', 'reference isolation', 'video binding and Range', 'save and reload', 'export/import', 'stale/invalid import rejection', 'exposure persistence', 'T3 future and pending', 'mobile layout'], screenshot_dir: output}));
  } finally {await browser.close();}
})().catch(error => {console.error(error); process.exitCode = 1;});
