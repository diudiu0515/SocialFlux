/* Run only against a server with experiment_hub.STORE pointing to a temp folder. */
const assert = require('node:assert/strict');
const { chromium } = require('playwright');
const base = process.env.LAB_TEST_URL;
if (!base || process.env.LAB_TEST_ISOLATED !== '1') throw Error('Set LAB_TEST_URL and LAB_TEST_ISOLATED=1 for an isolated test server.');
(async () => {
  const browser = await chromium.launch({ headless: true, args: ['--no-sandbox'] });
  const context = await browser.newContext({ viewport: { width: 1440, height: 1080 } });
  const page = await context.newPage();
  const errors = [];
  const uniqueTitle = '浏览器验证 ' + Date.now();
  page.on('pageerror', e => errors.push(e.message));
  try {
    await page.goto(base + '/lab');
    await page.waitForSelector('#stats .stat-card');
    assert.equal(await page.locator('#gate-summary .gate-step').count(), 4);
    assert.equal(await page.locator('#stats .stat-card').count(), 4);
    await page.click('a[data-view="matrix"]');
    assert.equal(await page.locator('#research-matrix tbody tr').count(), 16);
    assert.match(await page.locator('#research-matrix').innerText(), /约 30 个场景/);
    assert.match(await page.locator('#research-matrix').innerText(), /text\+caption/);
    await page.click('[data-edit="study-state-update-ablation"]');
    assert.match(await page.inputValue('[name="method"]'), /移除状态更新 prompt/);
    await page.click('#record-dialog .close');
    const matrixDownload = page.waitForEvent('download');
    await page.click('#export-matrix');
    assert.equal((await matrixDownload).suggestedFilename(), 'socialflux-experiment-matrix.csv');
    assert.match(await page.locator('#gate2-relation').innerText(), /Gate2 补充消融/);
    await page.click('a[data-view="paper"]');
    assert.equal(await page.locator('#paper-table tbody tr').count(), 9);
    assert.match(await page.locator('#paper-table').innerText(), /48\.84%/);
    assert.match(await page.locator('#paper-table').innerText(), /49\.87%/);
    await page.screenshot({path:'/tmp/socialflux-paper-tables.png',fullPage:true});
    await page.selectOption('#paper-select', 'gate-overview');
    assert.equal(await page.locator('#paper-table tbody tr').count(), 4);
    await page.selectOption('#paper-select', 'gate2-methods');
    assert.match(await page.locator('#paper-table').innerText(), /recent-k/);
    for(const [button,ext] of [['paper-markdown','md'],['paper-latex','tex'],['paper-csv','csv']]){
      const event=page.waitForEvent('download');await page.click('#'+button);
      assert.equal((await event).suggestedFilename(),'gate2-methods.'+ext);
    }
    await page.click('a[data-view="overview"]');
    await page.evaluate(() => document.fonts.ready);
    await page.screenshot({ path: '/tmp/socialflux-lab-desktop.png', fullPage: true });
    await page.click('#create');
    await page.fill('[name="title"]', uniqueTitle + ' <img src=x onerror=alert(1)>');
    await page.selectOption('[name="category"]', 'T4');
    await page.fill('[name="owner"]', '测试人员');
    await page.fill('[name="hypothesis"]', '验证保存、重新读取和跨浏览器更新。');
    await page.fill('[name="metrics_text"]', 'accuracy | 0.82 | ratio | 100');
    await page.fill('[name="sources_text"]', 'reports/experiments/2026-10-20_t4_checkpoint_findings.md');
    await page.click('#save-record');
    await page.waitForFunction(() => !document.getElementById('record-dialog').open);
    await page.click('a[data-view="plans"]');
    await page.fill('#plan-search', uniqueTitle);
    assert.equal(await page.locator('.plan-card').count(), 1);
    assert.equal(await page.locator('.plan-card img').count(), 0);
    await page.reload();
    await page.waitForSelector('.plan-card');
    await page.fill('#plan-search', uniqueTitle);
    await page.click('.plan-card [data-edit]');
    assert.equal(await page.inputValue('[name="owner"]'), '测试人员');
    assert.match(await page.inputValue('[name="metrics_text"]'), /0.82.*100/);
    await page.selectOption('[name="status"]', 'running');
    await page.fill('[name="notes"]', '已完成第一轮，等待复核。');
    await page.click('#save-record');
    await page.waitForFunction(() => !document.getElementById('record-dialog').open);
    await page.click('[data-status="running"]');
    assert.equal(await page.locator('.plan-card').count(), 1);
    const second = await browser.newContext();
    const other = await second.newPage();
    await other.goto(base + '/lab#plans');
    await other.waitForSelector('.plan-card');
    await other.fill('#plan-search', uniqueTitle);
    assert.match(await other.locator('.plan-card').innerText(), /进行中/);
    await other.click('.plan-card [data-edit]');
    assert.equal(await other.inputValue('[name="notes"]'), '已完成第一轮，等待复核。');
    await second.close();
    await page.click('a[data-view="results"]');
    assert.equal(await page.locator('#gate2-results tbody tr').count(), 9);
    assert.ok(await page.locator('.run-panel').count() >= 3);
    assert.match(await page.locator('#run-results').innerText(), /N\/A/);
    await page.click('a[data-view="library"]');
    await page.fill('#report-search', '2026-10-20_t4_checkpoint_findings.md');
    assert.equal(await page.locator('.report-entry').count(), 1);
    await page.click('.report-entry [data-source]');
    await page.waitForSelector('#source-content pre');
    assert.match(await page.locator('#source-content').innerText(), /36 次/);
    assert.match(await page.locator('#source-meta').innerText(), /SHA-256/);
    const fileDownload = page.waitForEvent('download');
    await page.click('#download-source');
    assert.equal((await fileDownload).suggestedFilename(), '2026-10-20_t4_checkpoint_findings.md');
    await page.click('#source-dialog .close');
    const jsonDownload = page.waitForEvent('download');
    await page.click('#export-all');
    assert.match((await jsonDownload).suggestedFilename(), /\.json$/);
    await page.setViewportSize({width: 390, height: 844});
    for (const tab of ['overview','matrix','paper','plans','results','library']) {
      await page.click(`a[data-view="${tab}"]`);
      await page.waitForSelector(`#${tab}-view`, {state: 'visible'});
      assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 2), tab + ' overflow');
    }
    await page.click('a[data-view="overview"]');
    await page.waitForSelector('#overview-view', {state: 'visible'});
    await page.screenshot({path: '/tmp/socialflux-lab-mobile.png', fullPage: true});
    await page.click('#create');
    assert.ok(await page.locator('#record-dialog').isVisible());
    assert.ok(await page.evaluate(() => document.getElementById('record-dialog').getBoundingClientRect().right <= innerWidth));
    await page.click('#record-dialog .close');
    await page.route('**/api/lab', route => route.fulfill({status: 503, contentType: 'application/json', body: '{"error":"temporary unavailable"}'}));
    await page.click('#refresh');
    await page.waitForFunction(() => !document.getElementById('error').hidden);
    assert.match(await page.locator('#error').innerText(), /上次数据/);
    assert.equal(await page.locator('#stats .stat-card').count(), 4);
    assert.deepEqual(errors, []);
    console.log(JSON.stringify({passed:true, checks:['live evidence','persistent create/edit','separate browser','XSS escaping','report search and source','file and JSON exports','mobile all views','refresh failure preserves snapshot']}));
  } finally { await browser.close(); }
})().catch(e => {console.error(e);process.exitCode = 1;});
