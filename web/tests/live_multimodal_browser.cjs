/* Run against a local review server with Playwright available in NODE_PATH. */
const {chromium} = require('playwright');
const assert = require('node:assert/strict');
(async () => {
  const browser = await chromium.launch({headless:true, args:['--no-sandbox']});
  const base = process.env.MULTIMODAL_TEST_URL || 'http://127.0.0.1:8011';
  const errors = [];
  try {
    const page = await browser.newPage({viewport:{width:1440,height:1100}});
    page.on('pageerror', error => errors.push(error.message));
    await page.goto(base + '/gpt50-live#GPT50_002');
    await page.waitForSelector('[data-mm-play]');
    assert.match(await page.locator('[data-mm-binding]').innerText(), /独立素材预览/);
    await page.locator('[data-mm-evidence] summary').click();
    assert.match(await page.locator('[data-mm-evidence]').innerText(), /ommv2_relationship_perceived_responsiveness_up/);
    assert.match(await page.locator('[data-mm-evidence]').innerText(), /视频待补/);
    await page.locator('#showMultimodal').click();
    await page.locator('[data-mm-play]').click();
    await page.waitForFunction(() => document.querySelector('video').currentTime > 0.1);
    assert.deepEqual(await page.locator('video').evaluate(v => ({muted:v.muted, volume:v.volume})), {muted:false,volume:1});
    await page.evaluate(() => { window.__originalVideo=document.querySelector('video'); renderDetail(); });
    assert.ok(await page.evaluate(() => document.querySelector('video') === window.__originalVideo));
    await page.waitForFunction(() => !document.querySelector('video').paused);
    await page.locator('video').evaluate(v => v.pause());
    await page.locator('[data-mm-evidence] summary').click();
    await page.locator('#multimodalSection').screenshot({path:'/tmp/emotree-multimodal-desktop.png'});
    await page.locator('[data-mm-lane="talking_head"]').click();
    assert.match(await page.locator('video').getAttribute('src'), /^\/talking-video\/gpt\//);
    assert.match(await page.locator('[data-mm-binding]').innerText(), /独立素材预览/);
    await page.locator('[data-mm-play]').click();
    await page.waitForFunction(() => document.querySelector('video').currentTime > 0.1);
    await page.locator('[data-id="GPT50_003"]').click();
    await page.waitForFunction(() => document.querySelector('video')?.getAttribute('src')?.includes('gpt50_003'));
    await page.locator('[data-mm-evidence] summary').click();
    assert.match(await page.locator('[data-mm-evidence]').innerText(), /ommv2_emotion_anxiety_down/);
    assert.equal(await page.locator('video').evaluate(v => v.paused), true);
    await page.locator('[data-mm-lane="talking_head"]').click();
    assert.equal(await page.locator('video').count(), 0);
    assert.match(await page.locator('[data-mm-player]').innerText(), /暂无可播放素材/);
    await page.locator('[data-mm-lane="all"]').click();
    await page.setViewportSize({width:390,height:844});
    await page.locator('#showMultimodal').click();
    await page.locator('#multimodalSection').evaluate(el => el.scrollIntoView({behavior:'instant', block:'start'}));
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth + 1), 'mobile horizontal overflow');
    await page.screenshot({path:'/tmp/emotree-multimodal-mobile.png'});
    await page.route('**/api/online-multimodal-review/gpt', route => route.fulfill({status:503,body:'unavailable'}));
    await page.locator('[data-mm-retry]').click();
    await page.waitForSelector('#multimodalSection [role="alert"]');
    assert.equal(await page.locator('#rolloutSection').count(), 1);
    await page.unroute('**/api/online-multimodal-review/gpt');
    await page.locator('[data-mm-retry]').click();
    await page.waitForSelector('video');
    await page.locator('.mm-review-link').click();
    await page.waitForSelector('#scenarioHeader h2');
    assert.ok(await page.evaluate(() => activeScenarioId === 'GPT50_003'));
    assert.deepEqual(errors, []);
    console.log('PASS: real state and talking-head playback, unmuted audio, refresh continuity, scenario and lane switches, empty lane, mobile layout, API error/retry, exact-scene review link; no page errors.');
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode=1; });
