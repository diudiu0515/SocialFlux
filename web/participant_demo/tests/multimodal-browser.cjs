// Local isolated D1 only. Pass {url, invite, output, legacyCode, legacyAlias} on stdin.
const assert = require('node:assert/strict');
const fs = require('node:fs');
const {createHash} = require('node:crypto');
const {chromium} = require('playwright');
(async () => {
  const {url, invite, output, legacyCode, legacyAlias} = JSON.parse(fs.readFileSync(0, 'utf8'));
  assert.match(url, /^http:\/\/127\.0\.0\.1:\d+$/);
  const browser = await chromium.launch({headless: true, args: ['--no-sandbox']});
  const errors = [], checks = [];
  const context = await browser.newContext({viewport: {width: 1440, height: 1050}});
  const page = await context.newPage();
  const watch = p => {p.on('pageerror', e => errors.push(e.message)); p.on('dialog', d => d.accept());};
  watch(page);
  const call = (p, action, body) => p.evaluate(async ({action, body}) => {
    const response = await fetch('/api/demo/' + action, body === undefined ? {} : {
      method: 'POST', headers: {'Content-Type': 'application/json'}, body: JSON.stringify(body)});
    return {status: response.status, body: await response.json()};
  }, {action, body});
  const saved = p => p.waitForFunction(() => document.querySelector('.review-save [role=status]')?.textContent === '进度已保存');
  const choose = (p, name, value) => p.locator(`label:has(input[name="${name}"][value="${value}"])`).click();
  const mediaReady = p => p.waitForFunction(() => {const v = document.querySelector('video'); return v && v.readyState >= 1 && v.videoWidth > 0 && v.duration > 0;});
  const recover = async (p, alias, code) => {
    await p.goto(url); await p.getByRole('button', {name: '恢复进度', exact: true}).click();
    await p.locator('#alias').fill(alias); await p.locator('#recovery-code').fill(code);
    await p.getByRole('button', {name: '恢复我的标注'}).click();
  };
  try {
    await page.goto(url); await page.getByText('准备好你的独立判断').waitFor();
    assert.equal((await call(page, 'status')).body.questions, undefined);
    assert.equal((await call(page, 'export')).status, 401);
    assert.equal((await call(page, 'access', {invite: 'bad'})).status, 403);
    await page.goto(url + '/#invite=' + invite); await page.reload();
    await page.waitForFunction(() => !document.querySelector('button.primary')?.disabled);
    await page.screenshot({path: output + '/welcome-desktop.png', fullPage: true});
    const alias = 'qa-media-' + Date.now();
    await page.locator('#alias').fill(alias); await page.locator('#exposure').selectOption('no'); await page.locator('#consent').check();
    await page.getByRole('button', {name: '进入标注空间'}).click();
    await page.locator('#issued-recovery').waitFor(); const recovery = await page.locator('#issued-recovery').inputValue();
    await page.getByRole('button', {name: '我已保存，进入场景审核'}).click(); await page.locator('#save-next-video').waitFor();
    const initial = (await call(page, 'status')).body;
    assert.equal(initial.videos.length, 52); assert.equal(initial.scenes.length, 45); assert.equal(initial.questions.length, 270);
    assert.equal(initial.videos.filter(v => v.kind === 'talking_head').length, 7);
    assert.equal(initial.dataset.kind, 'multimodal_review');
    for (const key of ['target_spec', 'oracle', 'provider_task_id', 'recoveryCode', 'user_id']) assert.equal(JSON.stringify(initial).includes('"' + key + '"'), false);
    checks.push('anonymous invitation and public-only 52/45/270 bundle');
    await mediaReady(page);
    await page.locator('video').evaluate(async video => {video.muted = true; video.currentTime = video.duration - 0.15; await video.play();});
    await page.waitForFunction(() => document.querySelector('#media-watched')?.checked === true);
    await choose(page, 'media-verdict', 'usable'); await page.locator('#media-watched').check();
    await page.locator('#save-next-video').click(); await page.locator('.spoken-script').waitFor(); await mediaReady(page);
    assert.equal(await page.locator('.spoken-script p[lang=en]').textContent(), initial.videos[1].spoken_text);
    await choose(page, 'media-verdict', 'revise'); await choose(page, 'media-issue', 'unnatural');
    await page.locator('#media-note').fill('Local QA only: speech looks unnatural.'); await page.locator('#media-watched').check();
    await page.screenshot({path: output + '/talking-desktop.png', fullPage: true});
    for (const width of [390, 360]) {
      await page.setViewportSize({width, height: 844});
      assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
      await page.screenshot({path: output + '/review-mobile-' + width + '.png', fullPage: true});
    }
    await page.getByRole('tab', {name: '题目作答 · 选填'}).click();
    await choose(page, 'answer', 'A'); await choose(page, 'confidence', 'medium');
    await page.getByRole('button', {name: '保存答案和视频审核'}).click(); await saved(page);
    const firstSaved = (await call(page, 'status')).body;
    assert.equal(Object.keys(firstSaved.session.answers).length, 1);
    assert.equal(Object.keys(firstSaved.session.mediaReviews).length, 2);
    assert.equal(firstSaved.session.mediaReviews[initial.videos[1].asset_id].verdict, 'revise');
    await page.screenshot({path: output + '/question-mobile.png', fullPage: true});
    checks.push('native playback, English script, independent optional answer and video review, mobile layout');
    await page.setViewportSize({width: 1440, height: 1050}); await page.getByRole('tab', {name: '视频可用性', exact: true}).click();
    await page.locator('#scene-select').selectOption(initial.scenes.at(-1).scene_id);
    await choose(page, 'media-verdict', 'uncertain'); await page.locator('#media-watched').check(); await saved(page);
    await page.locator('#scene-select').selectOption(initial.scenes[2].scene_id);
    await choose(page, 'media-verdict', 'usable'); await page.locator('#media-watched').check(); await saved(page);
    let previousRevision = (await call(page, 'status')).body.session.revision;
    await page.waitForTimeout(1700);
    assert.equal((await call(page, 'status')).body.session.revision, previousRevision);
    assert.equal(await page.getByRole('button', {name: '退出', exact: true}).isEnabled(), true);
    checks.push('out-of-order scene review saves once without retry loop');
    const second = await browser.newContext({viewport: {width: 1440, height: 1050}}), resume = await second.newPage(); watch(resume);
    await recover(resume, alias, recovery); await resume.locator('#save-next-video').waitFor();
    const restored = (await call(resume, 'status')).body;
    assert.equal(restored.session.id, initial.session.id); assert.deepEqual(restored.session.answers, firstSaved.session.answers);
    assert.equal(await resume.locator('#scene-select').inputValue(), initial.scenes[1].scene_id);
    assert.equal((await call(resume, 'recover', {alias: 'wrong', recoveryCode: recovery})).status, 401);
    assert.equal((await call(resume, 'draft', {revision: restored.session.revision, answers: {}, mediaReviews: {foreign: {verdict: 'usable'}}})).status, 400);
    assert.equal((await call(resume, 'submit', {revision: restored.session.revision, answers: restored.session.answers, mediaReviews: restored.session.mediaReviews, attestation: true})).status, 400);
    await choose(resume, 'media-verdict', 'usable'); await resume.locator('#media-watched').check(); await saved(resume);
    await page.locator('#media-note').fill('Local stale draft must survive a version conflict.');
    await page.getByRole('alert').filter({hasText: '另一页面更新'}).waitFor();
    assert.match(await page.locator('#media-note').inputValue(), /stale draft/);
    await page.reload(); await page.getByRole('button', {name: '下载旧草稿', exact: true}).waitFor();
    assert.equal(await page.evaluate(() => Object.keys(localStorage).some(key => key.startsWith('sf-media-conflict-'))), true);
    await page.reload(); await page.getByRole('button', {name: '下载旧草稿', exact: true}).waitFor();
    checks.push('cross-device recovery, incomplete rejection, stale draft preservation across reloads');
    for (let start = 0; start < initial.videos.length; start += 4) {
      await Promise.all(initial.videos.slice(start, start + 4).map(async video => {
        const response = await resume.request.get(url + video.url, {headers: {Range: 'bytes=0-1023'}});
        // The local assets simulator may return the complete file for Range requests.
        assert.ok([200, 206].includes(response.status()));
        const bytes = await response.body();
        if (response.status() === 206) assert.equal(bytes.length, 1024);
        else assert.equal(createHash('sha256').update(bytes).digest('hex'), video.sha256);
        assert.match(response.headers()['content-type'], /video\/mp4/);
      }));
    }
    checks.push('all 52 video URLs serve verified MP4 bytes; native seek and playback-end confirmation');
    const current = (await call(resume, 'status')).body;
    const reviews = Object.fromEntries(initial.videos.map(v => [v.asset_id, {verdict: 'usable', issues: [], note: 'Isolated QA fixture', watched: true}]));
    reviews[initial.videos[1].asset_id] = firstSaved.session.mediaReviews[initial.videos[1].asset_id];
    const body = {answers: current.session.answers, mediaReviews: reviews, revision: current.session.revision, attestation: true};
    const qid = Object.keys(body.answers)[0];
    assert.equal((await call(resume, 'submit', {...body, answers: {[qid]: {...body.answers[qid], confidence: ''}}})).status, 400);
    assert.equal((await call(resume, 'submit', {...body, attestation: false})).status, 400);
    assert.equal((await call(resume, 'draft', body)).status, 200);
    await resume.reload(); await resume.getByRole('button', {name: '检查提交', exact: true}).click();
    await resume.locator('#submit-media').waitFor(); assert.equal(await resume.locator('#submit-media').isDisabled(), true);
    await resume.locator('#media-attestation').check(); await resume.screenshot({path: output + '/summary-desktop.png', fullPage: true});
    await resume.locator('#submit-media').click(); await resume.getByText('52 段视频，你的判断已保存。').waitFor();
    const submitted = (await call(resume, 'status')).body;
    assert.equal(submitted.session.status, 'submitted');
    assert.equal((await call(resume, 'draft', {...body, revision: submitted.session.revision})).status, 409);
    assert.equal((await call(resume, 'submit', body)).body.session.submittedAt, submitted.session.submittedAt);
    const exported = (await call(resume, 'export')).body;
    assert.equal(exported.format, 'socialflux_multimodal_review_v1'); assert.equal(exported.formal_ground_truth, false);
    assert.equal(Object.keys(exported.media_reviews).length, 52); assert.equal(Object.keys(exported.media_hashes).length, 52);
    assert.equal(Object.keys(exported.answers).length, 1); assert.equal(Object.keys(exported.item_hashes).length, 270);
    for (const secret of [invite, recovery]) assert.equal(JSON.stringify(exported).includes(secret), false);
    await resume.reload(); await resume.getByText('52 段视频，你的判断已保存。').waitFor();
    await resume.setViewportSize({width: 360, height: 780}); assert.equal(await resume.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
    await resume.screenshot({path: output + '/receipt-mobile.png', fullPage: true});
    checks.push('52 reviews with one optional answer submit, lock, retry, export, and persist');
    const third = await browser.newContext(), legacy = await third.newPage(); watch(legacy);
    await recover(legacy, legacyAlias, legacyCode); await legacy.locator('#save-next').waitFor();
    const old = (await call(legacy, 'status')).body;
    assert.equal(old.questions.length, 6); assert.equal(old.videos.length, 0); assert.equal(old.dataset.kind, 'text');
    assert.equal(old.session.answers[old.questions[0].instance_id].answer, 'A');
    assert.equal((await call(legacy, 'submit', {answers: old.session.answers, revision: old.session.revision, attestation: true})).status, 400);
    const oldAnswers = Object.fromEntries(old.questions.map(q => [q.instance_id, {answer: 'A', confidence: 'high', rationale: 'Legacy QA only', issue: 'none'}]));
    assert.equal((await call(legacy, 'draft', {answers: oldAnswers, revision: old.session.revision})).status, 200);
    await legacy.reload(); await legacy.getByRole('button', {name: '检查提交', exact: true}).click();
    await legacy.locator('#attestation').check(); await legacy.locator('#submit-all').click(); await legacy.getByText('你的判断，已妥善保存。').waitFor();
    const oldExport = (await call(legacy, 'export')).body;
    assert.equal(oldExport.format, 'socialflux_public_demo_annotation_v1'); assert.equal(oldExport.modality, 'text');
    assert.equal(Object.keys(oldExport.answers).length, 6);
    checks.push('pre-migration six-question record restores and submits its frozen release');
    assert.equal((await resume.request.get(url + '/api/lab/records')).status(), 404); assert.deepEqual(errors, []);
    fs.writeFileSync(output + '/browser.json', JSON.stringify({passed: true, checks, browserErrors: errors}, null, 2));
    console.log('Browser checks passed: ' + checks.length + ' groups; 52 video URLs, native playback, legacy migration, desktop and mobile.');
  } finally {await browser.close();}
})().catch(error => {console.error(error); process.exit(1);});
