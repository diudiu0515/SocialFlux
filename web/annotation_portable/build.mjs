import {build} from 'vite';
import react from '@vitejs/plugin-react';
import {fileURLToPath} from 'node:url';
import {resolve} from 'node:path';
import {existsSync, readFileSync, writeFileSync, copyFileSync} from 'node:fs';
const root=fileURLToPath(new URL('.',import.meta.url));
const config=resolve(root,'dist/client/lab-config.js');
const previousConfig=existsSync(config)?readFileSync(config,'utf8'):null;
await build({root,configFile:false,plugins:[react()],base:'./',build:{outDir:resolve(root,'dist/client'),emptyOutDir:true}});
copyFileSync(resolve(root,'../pages/lab_bootstrap.js'),resolve(root,'dist/client/lab_bootstrap.js'));
const backend=process.env.LAB_BACKEND_URL||process.env.AutoDLService6006URL;
if(backend)writeFileSync(config,'window.SOCIALFLUX_BACKEND_URL='+JSON.stringify(backend.replace(/\/$/,''))+';\n');
else if(previousConfig)writeFileSync(config,previousConfig);
await build({root,configFile:false,publicDir:false,build:{ssr:resolve(root,'server.ts'),outDir:resolve(root,'dist/server'),emptyOutDir:true,rollupOptions:{output:{entryFileNames:'server.mjs'}}},ssr:{noExternal:['drizzle-orm']}});
