"""Qwen-only wire descriptions and diagnostic feedback; no state semantics.

The canonical appraisers/response validator remain the acceptance gates. This
module describes their interface and explains a previously rejected output; it
never repairs model output, adds a retry, or applies a state transition.
"""

from copy import deepcopy
import json

from jsonschema import Draft202012Validator

from environment.calibration import FEATURE_NAMES
from environment.independent_appraisal import JUDGMENT_LABELS
from environment.interaction_wire_schema import obj, text, array
from environment.ledger_events import semantic_ledger_wire_contract


def _nullable_enum(values):
    return {"enum": [None, *sorted(values)]}


def _judgments(paths):
    item = obj({
        "variable": text(paths), "judgment": text(JUDGMENT_LABELS),
        "direction": _nullable_enum(["increase", "decrease"]),
        "evidence_span": text(),
        "directness": _nullable_enum(["direct", "indirect"]),
        "evidence_feature": _nullable_enum(FEATURE_NAMES),
        "rationale": text(nonempty=True),
    })
    item["allOf"] = [{
        "if": {"properties": {"judgment": {"enum": [
            "ordinary_new_evidence", "decisive_new_evidence",
        ]}}},
        "then": {"properties": {
            "direction": text(["increase", "decrease"]),
            "directness": text(["direct", "indirect"]),
            "evidence_span": text(nonempty=True),
        }},
        "else": {"properties": {
            "direction": {"const": None}, "directness": {"const": None},
            "evidence_feature": {"const": None}, "evidence_span": {"const": ""},
        }},
    }]
    return array(item, minimum=len(paths), maximum=len(paths))


def state_schema(payload):
    return obj({
        "event_features": obj({name: {"type": "integer", "minimum": -2, "maximum": 2}
                               for name in FEATURE_NAMES}),
        "state_judgments": _judgments(payload["state_variable_paths"]),
        "dynamics_judgments": _judgments(payload["dynamics_variable_paths"]),
        "evidence_turn_ids": array(text(payload.get("memory", {}).get("relevant_turn_ids", [])),
                                   maximum=4, unique=True),
    })


def _event_schema(owner):
    registry = semantic_ledger_wire_contract()
    event = obj({
        "event_type": text(registry["event_status_pairs"]), "owner": text([owner]),
        "action_owner": text(registry["action_owners"]), "evidence_span": text(nonempty=True),
        "status": text({status for values in registry["event_status_pairs"].values() for status in values}),
        "assertion_mode": text(registry["assertion_modes"]),
    })
    event["allOf"] = [
        {"if": {"properties": {"event_type": {"const": kind}}},
         "then": {"properties": {"status": text(statuses)}}}
        for kind, statuses in registry["event_status_pairs"].items()
    ]
    return event


def interaction_schema(payload):
    # Generated by the canonical interaction owner for this exact context.
    schema = deepcopy(payload["output_schema"])
    schema["properties"]["appraisal"]["properties"]["ledger_events"]["items"] = _event_schema("evaluated_agent")
    return schema


def response_schema():
    return obj({
        "response_text": text(nonempty=True),
        "expression_intent": {**text(nonempty=True), "maxLength": 160},
        "observable_behavior": obj({
            **{key: text() for key in ("facial_expression", "gaze", "speech_style", "prosody")},
            "behavioral_cues": array(text(nonempty=True)),
        }),
        "ledger_events": array(_event_schema("environment_agent")),
        "reply_obligation": _nullable_enum(["evaluated_agent"]),
        "consequential_claims": array(obj({
            "claim_span": text(nonempty=True),
            # The canonical response validator has no domain enum. Do not
            # silently import the interaction appraiser's different contract.
            "impact_domains": array(text(nonempty=True)),
            "grounding": text(["observable_fact", "proposal_or_hypothetical",
                               "unsupported_assertion", "uncertain"]),
        }), maximum=3),
    })


def retry_feedback(raw, schema):
    """Explain field errors in an already rejected candidate, without mutation."""
    try:
        value = json.loads(raw)
    except (json.JSONDecodeError, TypeError) as exc:
        return "JSON syntax: " + str(exc)
    details = []
    for error in Draft202012Validator(schema).iter_errors(value):
        path = "$" + "".join(f"[{key}]" if isinstance(key, int) else "." + key
                              for key in error.absolute_path)
        details.append(f"{path}: {error.message}")
        if len(details) == 8:
            break
    return "\n".join(details) or (
        "No additional wire-shape error found. Follow the canonical validator's "
        "semantic error above; keep evidence, text and event annotations consistent."
    )
