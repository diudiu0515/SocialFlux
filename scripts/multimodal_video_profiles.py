def _event(trigger_id, variable, operator, threshold, *, face, gaze, head, timing,
           speech, prosody, cue):
    return {
        "trigger_id": trigger_id,
        "trigger_mode": "state_change",
        "conditions": {},
        "change_conditions": {
            variable: {"operator": operator, "threshold": threshold},
        },
        "priority": 1,
        "cooldown_turns": 3,
        "media_type": "video",
        "cue_template": trigger_id,
        "social_event": trigger_id,
        "duration_seconds": 6,
        "media_asset_id": None,
        "observable_expression": {
            "facial_expression": face,
            "gaze": gaze,
            "head_motion": head,
            "response_timing": timing,
            "speech_style": speech,
            "prosody": prosody,
            "behavioral_cues": [cue],
        },
    }


